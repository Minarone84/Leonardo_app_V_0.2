def _current_legend(
    family_id: str,
    *,
    owner_domain: str,
    owner_component: str,
    mutation_owner: str,
    read_provider: str,
    runtime_or_persistent: str,
    truth_source: str,
    required_identity_fields: tuple[str, ...],
    optional_identity_fields: tuple[str, ...] = (),
    metadata_fields: tuple[str, ...] = (),
    lifecycle_statuses: tuple[str, ...] = (),
    allowed_actions: tuple[str, ...] = (),
    permission_refs: tuple[str, ...] = (),
    audit_event_types: tuple[str, ...] = (),
    relationships_in: tuple[str, ...] = (),
    relationships_out: tuple[str, ...] = (),
    related_contracts: tuple[str, ...] = (),
    related_docs: tuple[str, ...] = (),
    related_tests: tuple[str, ...] = (),
    extra: Mapping[str, object] | None = None,
) -> ObjectFamilyLegend:
    return _legend(
        family_id,
        owner_domain=owner_domain,
        owner_component=owner_component,
        mutation_owner=mutation_owner,
        read_provider=read_provider,
        runtime_or_persistent=runtime_or_persistent,
        truth_source=truth_source,
        required_identity_fields=required_identity_fields,
        optional_identity_fields=optional_identity_fields,
        metadata_fields=metadata_fields,
        lifecycle_statuses=lifecycle_statuses,
        allowed_actions=allowed_actions or ("inspect",),
        permission_refs=permission_refs,
        audit_event_types=audit_event_types,
        relationships_in=relationships_in,
        relationships_out=relationships_out,
        related_contracts=related_contracts,
        related_docs=(_TRACEABLE_DOC, _LEGEND_DOC, *related_docs),
        related_tests=(_LEGEND_TEST, *related_tests),
        extra={"status": "current_v2", **dict(extra or {})},
    )



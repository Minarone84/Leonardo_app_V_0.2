_LEGENDS_BY_ID = MappingProxyType(
    {legend.family_id: legend for legend in OBJECT_FAMILY_LEGENDS}
)
_LEGENDS_BY_KIND = MappingProxyType(
    {legend.object_kind: legend for legend in OBJECT_FAMILY_LEGENDS}
)


def all_object_family_legends() -> tuple[ObjectFamilyLegend, ...]:
    """Return all static object family legends in deterministic order."""

    return OBJECT_FAMILY_LEGENDS


def object_family_legend_by_id(family_id: str) -> ObjectFamilyLegend | None:
    """Return a static family legend by family identifier."""

    _validate_lookup_key(family_id, "family_id")
    return _LEGENDS_BY_ID.get(family_id)


def object_family_legend_by_kind(object_kind: str) -> ObjectFamilyLegend | None:
    """Return a static family legend by object kind."""

    _validate_lookup_key(object_kind, "object_kind")
    return _LEGENDS_BY_KIND.get(object_kind)


def _validate_lookup_key(value: str, field_name: str) -> None:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{field_name} must be a non-empty string")


def _validate_unique_legends() -> None:
    if len(_LEGENDS_BY_ID) != len(OBJECT_FAMILY_LEGENDS):
        raise ValueError("Duplicate object family legend family_id")
    if len(_LEGENDS_BY_KIND) != len(OBJECT_FAMILY_LEGENDS):
        raise ValueError("Duplicate object family legend object_kind")


_validate_unique_legends()


def _future_permissions(owner_domain: str) -> tuple[str, ...]:
    if owner_domain.startswith("research"):
        return ("research:view",)
    if owner_domain.startswith("data_manager"):
        return ("data_manager:view",)
    if owner_domain.startswith("analysis"):
        return ("analysis:view",)
    if owner_domain.startswith("trading"):
        return ("trading:view",)
    if owner_domain.startswith("provider") or owner_domain.startswith("core.connection"):
        return ("connection:view",)
    return ("runtime:view",)


